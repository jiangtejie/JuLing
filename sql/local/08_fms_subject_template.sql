-- ============================================================================
-- 08_fms_subject_template.sql —— FMS 标准科目模板（账套初始化的科目来源）
--
-- 背景
--   FMS「账套初始化」读取本表，按账套的科目编码规则（默认 4-2-2-2）生成账套科目。
--   本表为空时 initializeDefaultSubjects 不建任何科目，随后 initializeClosingTemplates
--   会因结账模板预置引用的科目不存在而抛「结账模板【daily-travel-reimbursement】所需科目
--   【560107】不存在」，并回滚整个初始化事务 —— 账套永远初始化不成功。
--
-- 数据来源与口径（重要）
--   本文件是按《小企业会计准则》（财政部 财会〔2011〕17号，2013-01-01 施行）附录
--   《会计科目、主要账务处理和财务报表》+ 默认编码规则 4-2-2-2 **重构** 的版本，
--   不是厂商种子数据的导出。一级科目编码/名称来自准则附录（国家标准部分）；
--   明细科目的编码由厂商产品数据反推，名称按行业惯例命名。
--
--   编码来源（三处，已全部覆盖，共 94 条）：
--     1) fms/closing/closing-template-presets.json（21 张结账模板）
--        560107 报销差旅费 / 560101 电话费 / 560102 房租水电费 / 560110 工资 /
--        560209 工资 / 560302 利息收入 / 560303 手续费 / 22210101 进项税额 /
--        22210107 销项税额 / 222102 未交增值税 / 222111 应交所得税 / 222117 城建税 …
--     2) FmsClosingPresetSubjectEnum（结转损益、结转增值税等预置方案的专用科目）
--        6000 以前年度损益调整 / 310415 未分配利润 / 3103 本年利润 /
--        222101 应交增值税 / 22210104 转出未交增值税 / 222121 应交消费税 /
--        540303 城市维护建设税 / 540310 教育费附加 / 540313 地方教育费附加 /
--        222113 应交教育费附加 / 222114 应交地方教育费附加 / 5801 所得税费用 …
--     3) 增值税专栏 22210101~22210109 与财会〔2016〕22号《增值税会计处理规定》
--        的专栏顺序一致（01 进项税额、04 转出未交增值税、07 销项税额 均已校验命中），
--        故按该规定补齐 01~09 全部专栏。
--
--   两处按国家现行规定取、与厂商数据不一致的地方（编码不变，不影响功能）：
--     - 222102：厂商枚举 FmsClosingPresetSubjectEnum 把名称写作「销项税额」，但按
--       财会〔2016〕22号及结账模板语义（「缴纳增值税」借 222102）应为「未交增值税」；
--       枚举的 name 仅用于注释，程序只认编码。
--     - 5403：用 2016 年营改增后的现行名称「税金及附加」（原「营业税金及附加」）。
--
--   未生成：4404（FmsBalanceSheetServiceImpl.CAPITALIZED_EXPENSE_SUBJECT_CODE
--   「资本化支出」）—— 仅为「未纳入报表公式」提示的排除项，不存在也不影响初始化。
--
-- 前置条件
--   - 目标库为 PostgreSQL（本项目本地库 juling）；
--   - 账套尚未初始化成功（fms_account_set.initialized = false）。已初始化则不要执行本脚本，
--     应改为在「科目管理」里补科目或用 Excel 导入。
--
-- 幂等性
--   按 code 判重（本表无主键/唯一索引，不能用 ON CONFLICT），重复执行安全。
--   显式 id 从 1001 起分配：表为空时执行最安全。
--
-- 执行
--   psql -U root -d juling -f sql/local/08_fms_subject_template.sql
-- ============================================================================

